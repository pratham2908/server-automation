# Instagram's HTML header: the true UTC moment, printed on the downloader's clock (here UTC-8) but labelled "UTC".
HEADER = (
    '<aside>Generated by tryalgoviz on <time datetime="2026-11-06T12:51Z">Friday 6 November 2026 at 04:51 UTC</time>'
    "</aside>"
)
BLOCK = '<div class="pam _3-95 _2ph- _a6-g uiBoxWhite noborder">'
ME = "TryAlgoViz | Algorithm Visualizer"


def _dm(sender: str, text: str, at: str) -> str:
    return (
        f'{BLOCK}<h2 class="_3-95 _2pim _a6-h _a6-i">{sender}</h2><div class="_3-95 _a6-p"><div><div></div>'
        f'<div>{text}</div><div></div></div></div><div class="_3-94 _a6-o">{at}</div></div>'
    )


def _thread_page(title: str, messages: list[tuple[str, str, str]]) -> str:
    return f"<html><h1>{title}</h1>{HEADER}<main>" + "".join(_dm(*m) for m in messages) + "</main></html>"


REFUSED = "This account can&#039;t receive your message because they don&#039;t allow new message requests."
PRIVATE = "You sent a private reply to a comment on your Instagram post."


def test_the_header_gives_the_clock_shift_and_when_it_was_made() -> None:
    shift, generated = html_offset(HEADER)
    assert shift == timedelta(hours=-8)
    assert generated == datetime(2026, 11, 6, 12, 51, tzinfo=UTC)
    assert html_offset("<html>no header</html>") is None


def test_followers_html_reads_handles_and_true_follow_times() -> None:
    page = (
        f'{HEADER}{BLOCK}<div class="_a6-p"><div><div><a target="_blank" href="https://www.instagram.com/Ravi.K">'
        "Ravi.K</a></div><div>Nov 06, 2026 4:26 am</div></div></div></div>"
    )
    assert parse_followers_html(page, timedelta(hours=-8)) == {"ravi.k": datetime(2026, 11, 6, 12, 26, tzinfo=UTC)}


def test_a_thread_pairs_each_private_reply_with_its_refusal() -> None:
    page = _thread_page(
        "Aamir Ali",
        [
            (ME, REFUSED, "Nov 04, 2026 1:51 am"),
            (ME, PRIVATE, "Nov 04, 2026 1:51 am"),
            (ME, PRIVATE, "Nov 05, 2026 3:00 am"),
            ("Aamir Ali", "Hyderabad", "Nov 05, 2026 3:05 am"),
        ],
    )
    thread = thread_from_html("aamirali_2324262678331187", page, timedelta(hours=-8))
    assert thread is not None and thread.handle_hint == "aamirali" and thread.title == "Aamir Ali"
    assert thread.replies == [
        (datetime(2026, 11, 4, 9, 51, tzinfo=UTC), True),
        (datetime(2026, 11, 5, 11, 0, tzinfo=UTC), False),
    ]
    assert thread_from_html("123", _thread_page("x", [("x", "hi", "Nov 04, 2026 1:51 am")]), timedelta(0)) is None


def test_a_json_thread_too_with_its_latin1_mangled_text() -> None:
    at = int(datetime(2026, 11, 4, 9, 51, 30, tzinfo=UTC).timestamp() * 1000)
    data = {
        "title": "\u00c3\u0089ric",  # "Éric" as UTF-8 bytes read as Latin-1
        "messages": [
            {"sender_name": ME, "timestamp_ms": at, "content": "Not everyone can message this profile."},
            {"sender_name": ME, "timestamp_ms": at, "content": PRIVATE},
        ],
    }
    thread = thread_from_json("1234567", data)
    assert thread is not None and thread.title == "Éric" and thread.handle_hint == ""
    assert thread.replies == [(datetime(2026, 11, 4, 9, 51, tzinfo=UTC), True)]


T = datetime(2026, 11, 4, 9, 51, tzinfo=UTC)


class TestMatch:
    def test_a_handle_settles_who_when_a_minute_is_mixed(self) -> None:
        notices = [Notice(T, True, "aamirali"), Notice(T, False, "")]
        sent = [SentDm(1, T + timedelta(seconds=20), "aamir.ali"), SentDm(2, T + timedelta(seconds=40), "neha")]
        assert match(notices, sent) == {1: True, 2: False}

    def test_a_minute_that_agrees_is_assigned_whole(self) -> None:
        notices = [Notice(T, False, ""), Notice(T, False, "")]
        sent = [SentDm(1, T, "a"), SentDm(2, T + timedelta(seconds=59), "b")]
        assert match(notices, sent) == {1: False, 2: False}

    def test_a_mixed_minute_without_handles_is_left_unchecked(self) -> None:
        notices = [Notice(T, True, ""), Notice(T, False, "")]
        assert match(notices, [SentDm(1, T, "a"), SentDm(2, T, "b")]) == {}

    def test_more_sends_than_notices_isnt_guessed(self) -> None:
        assert match([Notice(T, True, "")], [SentDm(1, T, "a"), SentDm(2, T, "b")]) == {}

    def test_our_stamp_a_minute_later_still_matches(self) -> None:
        assert match([Notice(T, True, "")], [SentDm(1, T + timedelta(seconds=70), "a")]) == {1: True}


