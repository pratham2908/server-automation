# --- the import route with an HTML export --------------------------------------------------------


def _html_zip(handles: list[tuple[str, str]], threads: dict[str, str]) -> bytes:
    rows = "".join(
        f'{BLOCK}<div class="_a6-p"><div><div><a target="_blank" href="https://www.instagram.com/{h}">{h}</a></div>'
        f"<div>{at}</div></div></div></div>"
        for h, at in handles
    )
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as z:
        z.writestr("connections/followers_and_following/followers_1.html", f"<html>{HEADER}<main>{rows}</main></html>")
        for folder, page in threads.items():
            z.writestr(f"your_instagram_activity/messages/inbox/{folder}/message_1.html", page)
    return buf.getvalue()


