def test_an_html_export_imports_followers_and_dm_delivery(wired: Any) -> None:
    client, db = wired
    page = _thread_page("Aamir", [(ME, REFUSED, "Nov 04, 2026 1:51 am"), (ME, PRIVATE, "Nov 04, 2026 1:51 am")])
    content = _html_zip([("ravi", "Nov 06, 2026 4:26 am"), ("neha", "Oct 20, 2026 9:00 pm")], {"aamirali_1": page})
    res = client.post(
        "/api/v1/channels/zk/followers/import",
        files={"file": ("instagram-tryalgoviz-2026-11-06-x.zip", content, "application/zip")},
    )
    assert res.status_code == 200, res.text
    body = res.json()
    assert body["count"] == 2 and body["first_import"] is True
    # Dated by the export's own header (12:51 UTC = 18:21 IST), not the end of the zip's day.
    assert body["taken_at"].startswith("2026-11-06T18:21")
    assert body["dm_delivery"]["dms_refused"] == 1
    ravi = next(d for d in db.followers.docs if d["username"] == "ravi")
    assert ravi["followed_at"] == datetime(2026, 11, 6, 12, 26, tzinfo=UTC)
    assert db.comment_dm_events.docs[0]["delivery"] == "refused"
    assert json.loads(json.dumps(body))  # serialisable
